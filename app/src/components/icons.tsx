export type IconName = keyof typeof BITMAPS;
export const iconNames = Object.keys(BITMAPS) as IconName[];

const cache = new Map<IconName, string>();
function pathFor(name: IconName) {
  let d = cache.get(name);
  if (!d) {
    d = "";
    BITMAPS[name].forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === "#") d += `M${x + 0.07} ${y + 0.07}h0.86v0.86h-0.86z`;
    });
    cache.set(name, d);
  }
  return d;
}

/** Decorative by default; pass `label` when the icon is the only thing that says what a control does. */
export function Icon({ name, size = 24, color, label }: { name: IconName; size?: number; color: string; label?: string }) {
  // The View keeps the icon above stepped SVG backgrounds on web and carries the accessibility props.
  return (
    <View
      style={{ width: size, height: size }}
      accessible={label ? true : undefined}
      accessibilityRole={label ? "image" : undefined}
      accessibilityLabel={label}
      accessibilityElementsHidden={!label}
      importantForAccessibility={label ? "yes" : "no-hide-descendants"}
    >
      <Svg width={size} height={size} viewBox="0 0 9 9">
        <Path d={pathFor(name)} fill={color} />
      </Svg>
    </View>
  );
}
