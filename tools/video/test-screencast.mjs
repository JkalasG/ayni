import puppeteer from "puppeteer-core";
import path from "path";
import { pathToFileURL } from "url";
import { here, WORK } from "./common.mjs";
import { Recorder } from "./recorder.mjs";
const browser = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new", args: ["--no-sandbox", "--allow-file-access-from-files"], defaultViewport: { width: 1280, height: 720, deviceScaleFactor: 1.5 } });
const page = await browser.newPage();
await page.evaluateOnNewDocument(() => { window.__SCENE = "s01-story"; window.__TIMINGS = [{start:0,end:1},{start:2,end:3},{start:4,end:5},{start:6,end:7},{start:8,end:9},{start:10,end:11},{start:12,end:13}]; });
await page.goto(pathToFileURL(path.join(here, "story.html")).href, { waitUntil: "networkidle0" });
const rec = new Recorder(page, path.join(WORK, "frames-test"));
await rec.start();
await page.evaluate(() => window.startScene());
const n = await rec.finish(path.join(WORK, "clips", "test.mp4"), 5);
await browser.close();
console.log("frames", n);
