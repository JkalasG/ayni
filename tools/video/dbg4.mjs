import puppeteer from "puppeteer-core";
const BASE = "https://ayni.devsjec.com", API = BASE + "/api";
const j = async (u, i) => { const r = await fetch(u, i); return r.json(); };
const users = await j(API + "/auth/demo/users");
const wara = users.find((u) => u.name === "Marisol");
const token = (await j(API + "/auth/demo", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ userId: wara.id }) })).token;
const H = { authorization: "Bearer " + token };
const groups = await j(API + "/groups", { headers: H });
const g = groups.find((x) => x.name.startsWith("Ahorro del barrio"));
const d = await j(API + "/groups/" + g.id, { headers: H });
const round = d.rounds.find((r) => r.status === "COLLECTING");
console.log("round", round?.number, round?.contributions.map((c) => c.status).join(","));
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new", args: ["--no-sandbox", "--lang=en-US"], defaultViewport: { width: 1440, height: 810 } });
const p = await b.newPage();
await p.evaluateOnNewDocument((t) => { localStorage.setItem("ayni_token", t); localStorage.setItem("ayni_lang", "en"); }, token);
await p.goto(`${BASE}/groups/${g.id}`, { waitUntil: "domcontentloaded" });
await new Promise((r) => setTimeout(r, 12000));
console.log((await p.evaluate(() => document.body.innerText)).split("\n").filter((l) => /pay|paid|PayPal|contribution/i.test(l)).slice(0, 14).join("\n"));
await b.close();
