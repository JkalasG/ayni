import puppeteer from "puppeteer-core";
const BASE = "https://ayni.devsjec.com", API = BASE + "/api";
const j = async (u, i) => (await fetch(u, i)).json();
const users = await j(API + "/auth/demo/users");
const rosa = users.find((u) => u.name.includes("Rosa"));
const token = (await j(API + "/auth/demo", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ userId: rosa.id }) })).token;
const groups = await j(API + "/groups", { headers: { authorization: "Bearer " + token } });
console.log(groups.map((g) => g.name + " " + g.status).join(" | "));
const g = groups.find((x) => x.name === "Pasanaku de los comerciantes");
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new", args: ["--no-sandbox", "--lang=en-US"], defaultViewport: { width: 1440, height: 810 } });
const p = await b.newPage();
await p.evaluateOnNewDocument((t) => { localStorage.setItem("ayni_token", t); localStorage.setItem("ayni_lang", "en"); }, token);
await p.goto(`${BASE}/groups/${g.id}`, { waitUntil: "domcontentloaded" });
await new Promise((r) => setTimeout(r, 25000));
console.log((await p.evaluate(() => document.body.innerText)).slice(0, 700));
await p.screenshot({ path: "work/check/dbg.png" });
await b.close();
